// @ts-check
import js from '@eslint/js'
import { defineConfig, globalIgnores } from 'eslint/config'
import tseslint from 'typescript-eslint'

// Folders that must stay free of React, the DOM, and the app layer: data adapters and, later, sim engines.
const PURE = ['src/data/**/*.{ts,tsx}', 'src/engine/**/*.{ts,tsx}']

// Flat config does not merge rule options: when two blocks set the same rule for the same file, the LAST block
// wins outright. So every block below restates the full option list it wants.
const NO_NETWORK = 'Network only in src/data/adapters/: every fetch goes through an adapter and its snapshot cache.'
const NO_DOM = 'data/ and engine/ must not touch the DOM.'
const NO_CLOCK = 'engine/ must not read the clock: take time as an argument.'
const NO_RANDOM = 'engine/ is deterministic: use the seeded RNG passed in.'

const NETWORK_NAMES = ['fetch', 'XMLHttpRequest', 'WebSocket', 'EventSource', 'WebTransport', 'RTCPeerConnection']
const NETWORK_GLOBALS = NETWORK_NAMES.map((name) => ({ name, message: NO_NETWORK }))
const NETWORK_PROPERTIES = [
  ...['window', 'globalThis', 'self'].flatMap((object) => NETWORK_NAMES.map((property) => ({ object, property, message: NO_NETWORK }))),
  { property: 'sendBeacon', message: NO_NETWORK },
]
const DOM_GLOBALS = [
  { name: 'document', message: NO_DOM },
  { name: 'window', message: NO_DOM },
]
const NONDETERMINISM_PROPERTIES = [
  { object: 'Math', property: 'random', message: NO_RANDOM },
  { object: 'Date', property: 'now', message: NO_CLOCK },
  { object: 'performance', property: 'now', message: NO_CLOCK },
  ...['globalThis', 'self'].flatMap((object) => [
    { object, property: 'Math', message: NO_RANDOM },
    { object, property: 'Date', message: NO_CLOCK },
    { object, property: 'performance', message: NO_CLOCK },
  ]),
]
const NO_UI_IMPORTS = {
  paths: [
    { name: 'react', message: 'No React in data/ or engine/.' },
    { name: 'react-dom', message: 'No React in data/ or engine/.' },
  ],
  patterns: [
    { group: ['react/*', 'react-dom/*'], message: 'No React in data/ or engine/.' },
    // "../app", "../../app/foo", "@/app", "@/app/foo"
    { regex: '^((\\.{1,2}/)+(.*/)?|@/)app(/|$)', message: 'data/ and engine/ must not import from app/.' },
  ],
}

export default defineConfig(
  // src/components/ui is generated by the shadcn CLI and is not ours to lint.
  // scripts/ are plain Node helpers.
  globalIgnores(['dist/', 'coverage/', 'docs/', 'scripts/', 'public/cesium/', 'src/components/ui/']),

  js.configs.recommended,
  tseslint.configs.recommended,

  // No network anywhere under src/ except the adapters.
  {
    files: ['src/**/*.{ts,tsx}'],
    ignores: ['src/data/adapters/**'],
    rules: {
      'no-restricted-globals': ['error', ...NETWORK_GLOBALS],
      'no-restricted-properties': ['error', ...NETWORK_PROPERTIES],
    },
  },

  // Pure folders import no UI code and use no DOM globals. Adapters may fetch; nothing else pure may.
  {
    files: PURE,
    ignores: ['src/data/adapters/**'],
    rules: {
      'no-restricted-imports': ['error', NO_UI_IMPORTS],
      'no-restricted-globals': ['error', ...NETWORK_GLOBALS, ...DOM_GLOBALS],
    },
  },
  {
    files: ['src/data/adapters/**/*.{ts,tsx}'],
    rules: {
      'no-restricted-imports': ['error', NO_UI_IMPORTS],
      'no-restricted-globals': ['error', ...DOM_GLOBALS],
    },
  },

  // Engines are deterministic: no Math.random, no clock.
  {
    files: ['src/engine/**/*.{ts,tsx}'],
    rules: {
      'no-restricted-properties': ['error', ...NETWORK_PROPERTIES, ...NONDETERMINISM_PROPERTIES],
      'no-restricted-syntax': [
        'error',
        { selector: "NewExpression[callee.name='Date'][arguments.length=0]", message: NO_CLOCK },
        { selector: "CallExpression[callee.name='Date']", message: NO_CLOCK },
      ],
    },
  },
)
